-- Календарь дивидендных выплат MOEX (режим расчётов T+1) и налоговый/DCA-контур (backend#93, backend#94).
-- Денежные и процентные величины хранятся как NUMERIC (INV-6).

CREATE TABLE marketdata.dividend_event (
    id                     BIGSERIAL      PRIMARY KEY,
    ticker                 TEXT           NOT NULL,
    issuer_name            TEXT           NOT NULL,
    record_date            DATE           NOT NULL,
    ex_dividend_date       DATE           NOT NULL,
    last_buy_date          DATE           NOT NULL,
    payment_date           DATE           NOT NULL,
    dividend_per_share_rub NUMERIC(14, 4) NOT NULL CHECK (dividend_per_share_rub > 0),
    yield_pct              NUMERIC(8, 4)  NOT NULL CHECK (yield_pct > 0),
    estimated_gap_pct      NUMERIC(8, 4)  NOT NULL CHECK (estimated_gap_pct > 0),
    currency               TEXT           NOT NULL DEFAULT 'RUB',
    CHECK (last_buy_date < ex_dividend_date),
    CHECK (ex_dividend_date <= record_date),
    CHECK (record_date < payment_date)
);

CREATE INDEX idx_dividend_event_upper_ticker
    ON marketdata.dividend_event (UPPER(ticker), record_date DESC);

CREATE INDEX idx_dividend_event_record_date
    ON marketdata.dividend_event (record_date DESC, ticker ASC);

